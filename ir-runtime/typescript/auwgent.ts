// ── Type-Safe Auwgent Wrapper ────────────────────────────────────────────

export class TypedAuwgent<
    IR extends AgentIRShape,
    CustomIntents = never,
    Output = IR['output'] extends null ? any : IR['output'],
    Tools = ToolRegistry<IR>
> {
    private native: InstanceType<typeof AuwgentNative>;
    private ir: IR;

    constructor(ir: IR, config: AuwgentConfig<IR>) {
        this.ir = ir;
        this.native = new AuwgentNative(JSON.stringify(ir));

        if (config.context) {
            this.native.setContext(config.context);
        }

        const requiredProviders = collectRequiredProviders(ir);
        const apiKeys = config.apiKeys ?? (config.geminiApiKey ? { geminiApiKey: config.geminiApiKey } : undefined);
        const shouldSetGemini =
            apiKeys?.geminiApiKey &&
            (requiredProviders.size === 0 || requiredProviders.has('gemini'));
        if (shouldSetGemini) {
            this.native.setGeminiDriver(apiKeys.geminiApiKey!);
        }

        // Register all tools — guaranteed complete by the type system
        for (const [name, handler] of Object.entries(config.tools)) {
            this.native.registerTool(name, handler as (args: any) => Promise<any>);
        }
    }

    /**
     * Register an intent callback for real-time streaming events.
     *
     * The engine auto-executes tools/workflows by default. This callback
     * lets you observe what's happening (for UI) and optionally control it.
     *
     * @example
     * ```ts
     * // Observe all intents
     * agent.onIntent((name, value) => {
     *   console.log(`[${name}]`, value);
     * });
     * ```
     */
    onIntent(handler: IntentHandler<IR, CustomIntents, Output, Tools>): void {
        this.native.onIntent(async (name: string, value: any) => {
            return (handler as any)(name, value);
        });
    }

    /**
     * Register multiple intent handlers using an object-style API.
     * This is the recommended way to handle intents with perfect type safety.
     *
     * @example
     * ```ts
     * agent.onHandlers({
     *   response_text: (v) => console.log(v.text),
     *   tool_call: (v) => {
     *     if (v.type === 'get_student') console.log(v.args.id);
     *   }
     * });
     * ```
     */
    onHandlers(handlers: IntentHandlers<IR, CustomIntents, Output, Tools>): void {
        this.onIntent(async (...args: any[]) => {
            const [name, value] = args;
            const h = handlers[name as keyof typeof handlers];
            if (h) return await (h as any)(value);
        });
    }

    /**
     * Register a partial intent callback for streaming updates.
     * Fires as YAML data streams in, BEFORE the intent block is complete.
     *
     * Observational only — no control/skip/override.
     */
    onIntentPartial(handler: PartialIntentHandler<IR, CustomIntents, Output, Tools>): void {
        this.native.onIntentPartial((name: string, value: any) => {
            (handler as any)(name, value);
        });
    }

    /**
     * Register multiple partial intent handlers using an object-style API.
     *
     * @example
     * ```ts
     * agent.onHandlersPartial({
     *   response_text: (v) => process.stdout.write(v.text ?? ''),
     *   tool_call: (v) => {
     *     if (v.type === 'get_student') console.log('Streaming args:', v.args);
     *   }
     * });
     * ```
     */
    onHandlersPartial(handlers: PartialIntentHandlers<IR, CustomIntents, Output, Tools>): void {
        this.onIntentPartial((...args: any[]) => {
            const [name, value] = args;
            const h = handlers[name as keyof typeof handlers];
            if (h) (h as any)(value);
        });
    }

    /** Run the agentic loop. Returns the exported session state. */
    async run(input?: string): Promise<SessionState> {
        const json = await this.native.run(input ?? null);
        return JSON.parse(json) as SessionState;
    }

    /** Export session state for persistence. */
    exportSession(): SessionState {
        return JSON.parse(this.native.exportSession()) as SessionState;
    }

    /** Import a previously exported session state. */
    importSession(session: SessionState): void {
        this.native.importSession(JSON.stringify(session));
    }

    /** Clear the session (fresh conversation). */
    clearSession(): void {
        this.native.clearSession();
    }

    /** Generate the system prompt (debugging). */
    generatePrompt(): string {
        return this.native.generatePrompt();
    }

    /** Get tool names defined in the IR. */
    getToolNames(): ExtractToolNames<IR>[] {
        return this.native.getToolNames() as ExtractToolNames<IR>[];
    }

    /** Get tool schemas (for introspection). */
    getToolSchemas(): IRToolDef[] {
        return JSON.parse(this.native.getToolSchemas()) as IRToolDef[];
    }

    /** Access the raw native binding for advanced usage. */
    get raw(): InstanceType<typeof AuwgentNative> {
        return this.native;
    }
}

// ── Factory Function ─────────────────────────────────────────────────────

/**
 * Create a type-safe Auwgent agent from an IR object.
 *
 * The IR object MUST be typed with `as const` for full type inference:
 * ```ts
 * const ir = JSON.parse(fs.readFileSync('main.agent.json', 'utf8')) as const;
 * const agent = createAuwgent(ir, { tools: { ... } });
 * ```
 *
 * @param ir - The Agent IR object (parsed from JSON)
 * @param config - Config with tools and optional API key
 * @returns A type-safe Auwgent instance
 */
export function createAuwgent<
    const IR extends AgentIRShape,
    CustomIntents = never,
    Output = any,
    Tools extends Record<string, any> = ToolRegistry<IR>
>(
    ir: IR,
    config: Omit<AuwgentConfig<IR>, 'tools'> & { tools: Tools }
): TypedAuwgent<IR, CustomIntents, Output, Tools> {
    return new TypedAuwgent<IR, CustomIntents, Output, Tools>(ir, config);
}

export function createAuwgentFromIRJson<
    const IR extends AgentIRShape,
    CustomIntents = never,
    Output = IR['output'] extends null ? any : IR['output'],
    Tools = ToolRegistry<IR>
>(
    irJson: string,
    config: AuwgentConfig<IR>,
): TypedAuwgent<IR, CustomIntents, Output, Tools> {
    const ir = JSON.parse(irJson) as IR;
    return new TypedAuwgent<IR, CustomIntents, Output, Tools>(ir, config as any);
}

// ── Helper: Load IR with type inference ──────────────────────────────────

/**
 * Parse an IR JSON string into a typed IR object.
 * Use with `as const` for full tool name inference.
 */
export function parseIR<const IR extends AgentIRShape>(json: string): IR {
    return JSON.parse(json) as IR;
}
